MU_TEST(test_strict_commitment_rejects_non_template){
    loadPqPub();
    uint8_t c[32];
    const uint8_t ws51[1] = { 0x51 };
    const uint8_t ws52[1] = { 0x52 };
    /* v2 needs authType 0x01 and witnessScript exactly OP_TRUE. */
    mu_assert_int_eq(0, buildVersionedAuthScriptCommitment(2, UNEURAI_AUTHTYPE_PQ, pqPub, sizeof(pqPub), ws52, 1, c));
    mu_assert_int_eq(0, buildVersionedAuthScriptCommitment(2, UNEURAI_AUTHTYPE_NOAUTH, NULL, 0, ws51, 1, c));
    /* v3 needs authType 0x02 and a compressed key. */
    uint8_t ec[33];
    fromHex(NODE_EC_PUBKEY_HEX, ec, sizeof(ec));
    mu_assert_int_eq(0, buildVersionedAuthScriptCommitment(3, UNEURAI_AUTHTYPE_PQ, pqPub, sizeof(pqPub), ws51, 1, c));
    mu_assert_int_eq(1, buildVersionedAuthScriptCommitment(3, UNEURAI_AUTHTYPE_ECDSA, ec, 33, ws51, 1, c));
    uint8_t notCompressed[33];
    memcpy(notCompressed, ec, 33);
    notCompressed[0] = 0x04;
    mu_assert_int_eq(0, buildVersionedAuthScriptCommitment(3, UNEURAI_AUTHTYPE_ECDSA, notCompressed, 33, ws51, 1, c));
    /* Only witness versions 1..3 have an address family. */
    mu_assert_int_eq(0, buildVersionedAuthScriptCommitment(4, UNEURAI_AUTHTYPE_PQ, pqPub, sizeof(pqPub), ws51, 1, c));
    uint8_t spk[34];
    mu_assert_int_eq(0, (int)buildVersionedAuthScriptScriptPubKey(0, c, spk, sizeof(spk)));
    mu_assert_int_eq(0, (int)buildVersionedAuthScriptScriptPubKey(4, c, spk, sizeof(spk)));
}

