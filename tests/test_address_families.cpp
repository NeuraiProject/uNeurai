MU_TEST(test_decode_every_family){
    struct { const char * addr; const char * spk; uint8_t ver; bool testnet; ScriptType type; } v[] = {
        { NODE_V1_ADDRESS,     NODE_V1_SPK,    1, true,  P2AUTHSCRIPT    },
        { NODE_PQ_V1_MAINNET,  NODE_PQ_V1_SPK, 1, false, P2AUTHSCRIPT    },
        { NODE_PQ_V2_ADDRESS,  NODE_PQ_V2_SPK, 2, true,  P2AUTHSCRIPT_V2 },
        { NODE_PQ_V2_MAINNET,  NODE_PQ_V2_SPK, 2, false, P2AUTHSCRIPT_V2 },
        { NODE_EC_V3_ADDRESS,  NODE_EC_V3_SPK, 3, true,  P2AUTHSCRIPT_V3 },
        { NODE_EC_V3_MAINNET,  NODE_EC_V3_SPK, 3, false, P2AUTHSCRIPT_V3 },
    };
    for(size_t i = 0; i < sizeof(v) / sizeof(v[0]); i++){
        uint8_t ver = 0, prog[32];
        bool testnet = !v[i].testnet;
        mu_assert_int_eq(1, authScriptAddressDecode(v[i].addr, &ver, &testnet, prog));
        mu_assert_int_eq(v[i].ver, ver);
        mu_check(testnet == v[i].testnet);
        mu_assert_string_eq(v[i].spk + 4, hold(toHex(prog, 32)));

        /* Script(address) builds the node's scriptPubKey … */
        Script s(v[i].addr);
        mu_assert_string_eq(v[i].spk, scriptHex(s));
        mu_check(s.type() == v[i].type);
        mu_assert_int_eq(v[i].ver, s.authScriptVersion());
        mu_assert_int_eq(v[i].ver, authScriptWitnessVersionOf(s.scriptArray, s.scriptLen));

        /* … and renders back to the same address through both overloads. */
        const ChainNetwork * net = v[i].testnet ? &NeuraiTest : &Neurai;
        mu_assert_string_eq(v[i].addr, hold(s.address(net)));
        const ChainNetworkPQ * pqNet = v[i].testnet ? &NeuraiPQTest : &NeuraiPQ;
        mu_assert_string_eq(v[i].addr, hold(s.address(pqNet)));
        const ChainNetworkPQ * pqNetV2 = v[i].testnet ? &NeuraiPQV2Test : &NeuraiPQV2;
        mu_assert_string_eq(v[i].addr, hold(s.address(pqNetV2)));

        /* TxOut(address) routes through the same decoder. */
        TxOut out(v[i].addr, 1000);
        mu_assert_string_eq(v[i].spk, scriptHex(out.scriptPubkey));
    }
}

