/* minunit reads its string arguments after the full expression, so a
 * temporary std::string's c_str() would dangle: keep a copy alive. */
static const char * hold(const string & v){
    static char ring[4][256];
    static int next = 0;
    char * slot = ring[next];
    next = (next + 1) % 4;
    strncpy(slot, v.c_str(), 255);
    slot[255] = '\0';
    return slot;
}

static const char * scriptHex(const Script & s){
    return hold(toHex(s.scriptArray, s.scriptLen));
}

